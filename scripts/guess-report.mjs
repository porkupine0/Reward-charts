// Writes docs/driving-guess-report.md: guessing tells per unit and form (driving.js guessReport).
// Run: node scripts/guess-report.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const V = JSON.parse(readFileSync(new URL('../version.json', import.meta.url))).v;
const D = await import('../driving.js?v=' + V), { LESSONS } = await import('../driving-course.js?v=' + V), { FORMS } = await import('../driving-tests.js?v=' + V);
const units = {};
LESSONS.forEach((l) => { const u = 'unit ' + l.id.match(/^w(\d+)/)[1]; (units[u] = units[u] || []).push(...(l.questions || [])); });
const out = ['# Guessing tells (report)', '', 'Generated by `node scripts/guess-report.mjs`. Rank = how often the right answer is the longest / 2nd / 3rd / shortest choice (keep each at 35% or less). A hard rule for units 5+ and Forms C+ (tests/driving.test.mjs); units 1-4 and Form B are reported until reworked; Form A is frozen (record only).', ''];
for (const [g, qs] of [...Object.entries(units), ...Object.entries(FORMS).map(([f, q]) => ['form ' + f, q])]) {
  const r = D.guessReport(g, qs);
  out.push('## ' + g + ': ' + r.ranks.join('/') + ' (worst ' + Math.round(r.worst * 100) + '%)', '', ...(r.issues.length ? r.issues.map((x) => '- ' + x) : ['- none']), '');
}
writeFileSync(new URL('../docs/driving-guess-report.md', import.meta.url), out.join('\n'));
console.log('written');
